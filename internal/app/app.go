// Package app assembles the HTTP handler: repositories -> handlers -> ServeMux -> middleware.
package app

import (
	"io/fs"
	"net/http"

	httpSwagger "github.com/swaggo/http-swagger/v2"

	_ "homework/docs" // generated by swag; registers the OpenAPI spec
	"homework/internal/handler"
	"homework/internal/middleware"
	"homework/internal/model"
	"homework/internal/repository"
)

// Config carries the settings the router needs beyond the repositories.
type Config struct {
	JWTSecret    string // signs and verifies login tokens; main refuses to start without it
	Templates    fs.FS  // html/template files of the web UI, embedded by package web
	Static       fs.FS  // static assets served under /static/, embedded by package web
	CookieSecure bool   // Secure flag of the web session cookie; switch it on behind TLS
}

// NewRouter builds the complete HTTP handler on top of the given repositories. Handlers
// depend on interfaces only, so tests can pass fakes and main passes GORM. Routes are
// registered in four groups (public, any authenticated user, staff, admin); every
// protected route is wrapped explicitly, Auth always before RequireRole, which is the
// net/http equivalent of nested route groups.
func NewRouter(repos repository.Repositories, cfg Config) http.Handler {
	if cfg.JWTSecret == "" {
		panic("app.NewRouter: JWTSecret is empty (set JWT_SECRET)")
	}
	if cfg.Templates == nil || cfg.Static == nil {
		panic("app.NewRouter: Templates and Static are required (pass web.Templates() and web.Static())")
	}
	albums := handler.NewAlbumHandler(repos.Albums)
	artists := handler.NewArtistHandler(repos.Artists)
	genres := handler.NewGenreHandler(repos.Genres)
	copies := handler.NewCopyHandler(repos.Copies)
	authn := handler.NewAuthHandler(repos.Users, cfg.JWTSecret)
	users := handler.NewUserHandler(repos.Users)

	protected := middleware.Auth(cfg.JWTSecret)
	staff := func(h http.HandlerFunc) http.Handler {
		return protected(middleware.RequireRole(model.UserRoleStaff, model.UserRoleAdmin)(h))
	}
	admin := func(h http.HandlerFunc) http.Handler {
		return protected(middleware.RequireRole(model.UserRoleAdmin)(h))
	}

	mux := http.NewServeMux()

	// Public: health, registration, login and every read of the catalogue.
	mux.HandleFunc("GET /health", handler.Health)
	mux.HandleFunc("POST /api/v1/auth/register", authn.Register)
	mux.HandleFunc("POST /api/v1/auth/login", authn.Login)
	mux.HandleFunc("GET /api/v1/genres", genres.List)
	mux.HandleFunc("GET /api/v1/genres/{id}", genres.Get)
	mux.HandleFunc("GET /api/v1/artists", artists.List)
	mux.HandleFunc("GET /api/v1/artists/{id}", artists.Get)
	mux.HandleFunc("GET /api/v1/albums", albums.List)
	mux.HandleFunc("GET /api/v1/albums/{id}", albums.Get)
	mux.HandleFunc("GET /api/v1/albums/{id}/copies", copies.List)
	mux.HandleFunc("GET /api/v1/albums/{id}/availability", copies.Availability)

	// Any authenticated user.
	mux.Handle("GET /api/v1/me", protected(http.HandlerFunc(authn.Me)))

	// Staff and admin: every write of the catalogue.
	mux.Handle("POST /api/v1/genres", staff(genres.Create))
	mux.Handle("POST /api/v1/artists", staff(artists.Create))
	mux.Handle("POST /api/v1/albums", staff(albums.Create))
	mux.Handle("PUT /api/v1/albums/{id}", staff(albums.Update))
	mux.Handle("DELETE /api/v1/albums/{id}", staff(albums.Delete))
	mux.Handle("POST /api/v1/albums/{id}/copies", staff(copies.Create))

	// Admin only: account management.
	mux.Handle("GET /api/v1/users", admin(users.List))
	mux.Handle("PUT /api/v1/users/{id}/role", admin(users.UpdateRole))

	mux.Handle("GET /swagger/", httpSwagger.WrapHandler) // Swagger UI: /swagger/index.html
	mux.HandleFunc("/", handler.NotFound)                // everything else: JSON 404

	// CORS answers every preflight before any route-level Auth sees it.
	return middleware.Logging(middleware.Recover(middleware.CORS(mux)))
}
